    check('Clear restores all mods and returns focus to search',await page.eval(()=>document.querySelectorAll('[data-mod]:not([hidden])').length===34 && document.activeElement.id==='mod-search'));
    await page.eval(()=>{const t=document.querySelector('#color-theme');t.value='dark';t.dispatchEvent(new Event('change',{bubbles:true}));});
