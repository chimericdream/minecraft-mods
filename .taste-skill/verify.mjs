import assert from 'node:assert/strict';
import {readFileSync,readdirSync,existsSync,statSync,writeFileSync} from 'node:fs';
import path from 'node:path';
import {Browser} from 'file:///C:/Users/bill/.codex/plugins/cache/taste-skill/taste-skill/2.1.4/skills/taste-skill/scripts/lib/cdp.mjs';
const root = path.resolve('site/dist');
const walk = dir => readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(path.join(dir,e.name)):[path.join(dir,e.name)]);
const htmlFiles = walk(root).filter(f=>f.endsWith('.html'));
const broken = [];
for(const file of htmlFiles) {
    const html=readFileSync(file,'utf8').replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'');
    for(const [,raw] of html.matchAll(/(?:href|src)="([^"]+)"/g)) {
        const href=raw.replaceAll('&amp;','&');
        if(/^(?:[a-z]+:|\/\/|#)/i.test(href))continue;
        assert(!href.startsWith('/'),`${file} has an absolute internal link: ${href}`);
        const target=decodeURIComponent(href.split(/[?#]/)[0]);
        const resolved=path.resolve(path.dirname(file),target);
        if(!existsSync(resolved) && !existsSync(path.join(resolved,'index.html')))broken.push({file:path.relative(root,file),href});
    }
}
assert.deepEqual(broken,[],'Every generated internal link and image must resolve');
const results = {htmlPages:htmlFiles.length,brokenLinks:broken,checks:[]};
const check=(name,value)=>{assert(value,name);results.checks.push(name);};
