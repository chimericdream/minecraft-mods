import {Browser} from 'file:///C:/Users/bill/.codex/plugins/cache/taste-skill/taste-skill/2.1.4/skills/taste-skill/scripts/lib/cdp.mjs';
import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
const b = await Browser.launch();
const passed = [];
try {
  const p = await b.newPage({width: 390, height: 844});
  await p.goto('http://localhost:5000/');
  assert.equal(await p.eval(() => document.querySelectorAll('.mod-row:not([hidden])').length), 30);
  await p.eval(() => {const input=document.querySelector('#mod-search'); input.value='minekea'; input.dispatchEvent(new Event('input'));});
  assert.equal(await p.eval(() => document.querySelectorAll('.mod-row:not([hidden])').length), 1);
  await p.eval(() => {const input=document.querySelector('#mod-search'); input.value='no-such-mod'; input.dispatchEvent(new Event('input'));});
  assert.equal(await p.eval(() => document.querySelector('#catalogue-empty').hidden), false);
  await p.eval(() => document.querySelector('#clear-search').click());
  assert.equal(await p.eval(() => document.querySelectorAll('.mod-row:not([hidden])').length), 30);
  passed.push('Catalogue: 30 default rows, featured search, empty state, clear');
  await p.eval(() => {const t=document.querySelector('#color-theme');t.value='light';t.dispatchEvent(new Event('change'));});
  await p.goto('http://localhost:5000/mods/minekea/');
  assert.equal(await p.eval(() => document.documentElement.dataset.theme), 'light');
  assert.equal(await p.eval(() => getComputedStyle(document.querySelector('.side-content')).display), 'none');
  await p.eval(() => document.querySelector('.side-toggle').click());
  assert.notEqual(await p.eval(() => getComputedStyle(document.querySelector('.side-content')).display), 'none');
  assert.equal(await p.eval(() => document.querySelector('.actions a').href), 'https://www.curseforge.com/projects/594052');
  passed.push('Theme persists across routes; phone navigation expands; download uses configured project');
  await p.goto('http://localhost:5000/ideas/');
  assert.equal(await p.eval(() => document.querySelectorAll('#color-theme').length), 1);
  assert.equal(await p.eval(() => document.querySelectorAll('#theme').length), 1);
  await p.eval(() => {const m=document.querySelector('#mod');m.value='minekea';m.dispatchEvent(new Event('change'));});
  assert.ok(await p.eval(() => [...document.querySelectorAll('#body tr')].every(row=>row.textContent.includes('Minekea'))));
  await p.eval(() => document.querySelector('#f-effort button').click());
  assert.equal(await p.eval(() => document.querySelector('#f-effort button').getAttribute('aria-pressed')), 'true');
  passed.push('Roadmap filters work independently of color theme; filter buttons expose pressed state');
  await p.eval(() => {const t=document.querySelector('#color-theme');t.value='system';t.dispatchEvent(new Event('change'));});
  await p.send('Emulation.setEmulatedMedia',{features:[{name:'prefers-color-scheme',value:'dark'},{name:'prefers-reduced-motion',value:'reduce'}]});
  await p.goto('http://localhost:5000/');
  assert.equal(await p.eval(() => getComputedStyle(document.body).backgroundColor), 'rgb(23, 18, 30)');
  assert.equal(await p.eval(() => document.getAnimations().length), 0);
  passed.push('System theme follows OS; reduced motion disables all animations');
  await p.send('Emulation.setScriptExecutionDisabled',{value:true});
  await p.goto('http://localhost:5000/');
  assert.equal(await p.eval(() => document.querySelectorAll('.mod-row:not([hidden])').length),30);
  passed.push('No-JavaScript catalogue retains all 34 mods across masthead and directory');
  assert.deepEqual(p.consoleErrors, []);
  passed.push('No runtime exceptions across exercised pages');
  writeFileSync('.taste-skill/check-results.json', JSON.stringify(passed,null,2)+'\n');
  console.log(passed.join('\n'));
} finally { await b.close(); }
